ZWSP = '\u200B'

def zwsp(text):
    if not text: return ""
    return ZWSP.join(word_tokenize(text, engine="newmm"))

def set_font(run, size=15, bold=False, color=None, fn="TH Sarabun New"):
    run.font.name = fn; run.font.size = Pt(size); run.bold = bold
    if color: run.font.color.rgb = RGBColor(*color)
    rPr = run._element.get_or_add_rPr(); rf = rPr.get_or_add_rFonts()
    for a in ('ascii','hAnsi','cs'): rf.set(a, fn)

def new_doc():
    doc = Document(); sec = doc.sections[0]
    for attr in ('left_margin','right_margin','top_margin','bottom_margin'):
        setattr(sec, attr, Cm(2.0))
    return doc

def h1(doc, text):
    p = doc.add_paragraph(); p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(zwsp(text)); set_font(r, 20, True)

def h2(doc, text, color=(31,73,125)):
    p = doc.add_paragraph(); r = p.add_run(zwsp("▌ " + text)); set_font(r, 17, True, color)

def para(doc, text, bold=False, size=15, indent=0):
    p = doc.add_paragraph()
    if indent: p.paragraph_format.left_indent = Cm(indent)
    r = p.add_run(zwsp(text)); set_font(r, size, bold)

def rule_box(doc, items):
    tbl = doc.add_table(1,1); tbl.style = 'Table Grid'
    cell = tbl.rows[0].cells[0]
    lp = cell.add_paragraph(); lr = lp.add_run(zwsp("⚠️ กฎเหล็กบังคับคิด"))
    set_font(lr, 15, True, (192,0,0))
    for item in items:
        ip = cell.add_paragraph(); ir = ip.add_run(zwsp(item)); set_font(ir, 14)
    cell.paragraphs[0]._element.getparent().remove(cell.paragraphs[0]._element)

def tbl(doc, headers, data):
    t = doc.add_table(1+len(data), len(headers)); t.style = 'Table Grid'
    for i,h in enumerate(headers):
        p = t.rows[0].cells[i].paragraphs[0]; p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(zwsp(h)); set_font(r, 14, True)
    for ri,row in enumerate(data):
        for ci,val in enumerate(row):
            p = t.rows[ri+1].cells[ci].paragraphs[0]; r = p.add_run(zwsp(val)); set_font(r, 14)
    return t

def save(doc, filename):
    doc.save(os.path.join(target_dir, filename))

