def set_font(run, size=16, bold=False, color_rgb=None):
    run.font.name = 'TH Sarabun New'
    run.font.size = Pt(size)
    run.bold = bold
    if color_rgb:
        run.font.color.rgb = color_rgb
    r = run._element
    rPr = r.get_or_add_rPr()
    rFonts = OxmlElement('w:rFonts')
    for attr in ['w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia']:
        rFonts.set(qn(attr), 'TH Sarabun New')
    rPr.append(rFonts)

def add_p(doc, text="", size=16, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, color_rgb=None, space_before=2, space_after=4):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.line_spacing = 1.15
    if text:
        r = p.add_run(text)
        set_font(r, size=size, bold=bold, color_rgb=color_rgb)
    return p

def format_cell(cell, text, size=14, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, bg_hex=None):
    cell.text = ""
    lines = text.split('\n')
    for idx, line in enumerate(lines):
        p = cell.paragraphs[0] if idx == 0 else cell.add_paragraph()
        p.alignment = align
        p.paragraph_format.space_before = Pt(2)
        p.paragraph_format.space_after = Pt(2)
        p.paragraph_format.line_spacing = 1.1
        r = p.add_run(line)
        set_font(r, size=size, bold=bold)
    if bg_hex:
        tcPr = cell._tc.get_or_add_tcPr()
        shd = OxmlElement('w:shd')
        shd.set(qn('w:val'), 'clear')
        shd.set(qn('w:color'), 'auto')
        shd.set(qn('w:fill'), bg_hex)
        tcPr.append(shd)

def setup_doc():
    doc = docx.Document()
    for section in doc.sections:
        section.top_margin = Cm(1.8)
        section.bottom_margin = Cm(1.8)
        section.left_margin = Cm(2.0)
        section.right_margin = Cm(2.0)
    style = doc.styles['Normal']
    style.font.name = 'TH Sarabun New'
    style.font.size = Pt(16)
    return doc

