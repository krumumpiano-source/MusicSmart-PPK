def add_p(text, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT, size=16):
    p = doc.add_paragraph()
    p.alignment = align
    run = p.add_run(insert_zwsp(text))
    run.font.name = 'TH Sarabun New'
    run.font.size = Pt(size)
    run.bold = bold
    return p

