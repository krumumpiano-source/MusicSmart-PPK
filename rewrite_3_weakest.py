ZWSP = '\u200B'

def zwsp(text):
    if not text: return ""
    return ZWSP.join(word_tokenize(text, engine="newmm"))

def set_font(run, size=16, bold=False, color=None, font_name="TH Sarabun New"):
    run.font.name = font_name
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    for attr in ('ascii', 'hAnsi', 'cs'):
        rFonts.set(attr, font_name)

def new_doc():
    doc = Document()
    sec = doc.sections[0]
    sec.left_margin = Cm(2.0)
    sec.right_margin = Cm(2.0)
    sec.top_margin = Cm(2.0)
    sec.bottom_margin = Cm(2.0)
    return doc

def add_h1(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(zwsp(text))
    set_font(r, size=20, bold=True)

def add_h2(doc, text, color=(31,73,125)):
    p = doc.add_paragraph()
    r = p.add_run(zwsp("▌ " + text))
    set_font(r, size=17, bold=True, color=color)

def add_p(doc, text, bold=False, size=15, color=None, indent=False):
    p = doc.add_paragraph()
    if indent:
        p.paragraph_format.left_indent = Cm(0.5)
    r = p.add_run(zwsp(text))
    set_font(r, size=size, bold=bold, color=color)

def add_box(doc, label, items, box_color=(198,224,180)):
    """Adds a visually distinct rule/notice box as a table with 1 cell."""
    table = doc.add_table(rows=1, cols=1)
    table.style = 'Table Grid'
    cell = table.rows[0].cells[0]
    cell._tc.get_or_add_tcPr()
    # Add label
    lp = cell.add_paragraph()
    lr = lp.add_run(zwsp(label))
    set_font(lr, size=15, bold=True, color=(192,0,0))
    for item in items:
        ip = cell.add_paragraph()
        ir = ip.add_run(zwsp(item))
        set_font(ir, size=14)
    # Remove default empty first paragraph
    cell.paragraphs[0]._element.getparent().remove(cell.paragraphs[0]._element)

def add_table_full(doc, headers, rows_data):
    """Add table with actual content in rows."""
    table = doc.add_table(rows=1 + len(rows_data), cols=len(headers))
    table.style = 'Table Grid'
    # Header row
    for i, h in enumerate(headers):
        p = table.rows[0].cells[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(zwsp(h))
        set_font(r, size=14, bold=True)
    # Data rows
    for ri, row_data in enumerate(rows_data):
        for ci, val in enumerate(row_data):
            p = table.rows[ri+1].cells[ci].paragraphs[0]
            r = p.add_run(zwsp(val))
            set_font(r, size=14)
    return table

