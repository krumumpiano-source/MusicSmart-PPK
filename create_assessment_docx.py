import os
from docx import Document
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from pythainlp.tokenize import word_tokenize

# Define the target directory
target_dir = r"D:\AI CURSER\PLANE MUSIC ED\เอกสารแผนการสอน\ม.1 ดนตรี1 ศ21101\เครื่องมือวัดผล"
os.makedirs(target_dir, exist_ok=True)

ZWSP = '\u200B'

def insert_zwsp(text):
    if not text: return ""
    tokens = word_tokenize(text, engine="newmm")
    return ZWSP.join(tokens)

def set_font(run, font_name="TH Sarabun New", size=16):
    run.font.name = font_name
    run.font.size = Pt(size)
    # Required for Thai font
    rPr = run._element.get_or_add_rPr()
    rFonts = rPr.get_or_add_rFonts()
    rFonts.set('ascii', font_name)
    rFonts.set('hAnsi', font_name)
    rFonts.set('cs', font_name)

def add_heading(doc, text):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run(insert_zwsp(text))
    set_font(run, size=18)
    run.bold = True

def add_paragraph(doc, text, bold=False):
    p = doc.add_paragraph()
    run = p.add_run(insert_zwsp(text))
    set_font(run, size=16)
    run.bold = bold

def add_rubric_table(doc, headers, data):
    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Table Grid'
    hdr_cells = table.rows[0].cells
    for i, h in enumerate(headers):
        p = hdr_cells[i].paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(insert_zwsp(h))
        set_font(run, size=16)
        run.bold = True

    for row_data in data:
        row_cells = table.add_row().cells
        for i, val in enumerate(row_data):
            p = row_cells[i].paragraphs[0]
            run = p.add_run(insert_zwsp(val))
            set_font(run, size=16)

def create_doc(filename, title, desc, headers, data, note=""):
    doc = Document()
    # Set page layout to A4 Landscape if table has many columns, else Portrait
    if len(headers) > 3:
        section = doc.sections[0]
        new_width, new_height = section.page_height, section.page_width
        section.page_width = new_width
        section.page_height = new_height
        section.left_margin = Cm(2.0)
        section.right_margin = Cm(2.0)
    else:
        section = doc.sections[0]
        section.left_margin = Cm(2.54)
        section.right_margin = Cm(2.54)

    add_heading(doc, title)
    for d in desc:
        add_paragraph(doc, d)
        
    doc.add_paragraph() # spacing
    add_rubric_table(doc, headers, data)
    
    if note:
        doc.add_paragraph()
        add_paragraph(doc, note, bold=True)
        
    doc.save(os.path.join(target_dir, filename))
    # print(f"Created: {filename}")

