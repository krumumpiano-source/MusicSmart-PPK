for item in tools_info:
    old_p = os.path.join(dp, item['old'])
    new_p = os.path.join(dp, item['new'])
    target_p = old_p if os.path.exists(old_p) else new_p
    
    if not os.path.exists(target_p):
        print(f"Warning: neither {old_p} nor {new_p} found.")
        continue
        
    doc = docx.Document(target_p)
    doc.paragraphs[0].text = item['title']
    
    if item['is_p4']:
        # If paragraph 1 was usage, we update P1 to course, P2 to usage, and preserve names
        doc.paragraphs[1].text = item['course']
        if len(doc.paragraphs) > 2 and 'ชื่อผู้ประเมิน' in doc.paragraphs[2].text:
            orig_p2 = doc.paragraphs[2].text
            doc.paragraphs[2].text = item['usage']
            if len(doc.paragraphs) > 3:
                doc.paragraphs[3].text = orig_p2
            else:
                doc.add_paragraph(orig_p2)
        else:
            doc.paragraphs[2].text = item['usage']
    else:
        doc.paragraphs[1].text = item['course']
        doc.paragraphs[2].text = item['usage']
        
    doc.save(new_p)
    if os.path.exists(old_p) and old_p != new_p:
        os.remove(old_p)
    print(f"Successfully processed: {item['new']}")

