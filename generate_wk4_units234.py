import docx
from docx.shared import Pt, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from pythainlp.tokenize import word_tokenize
import os

def insert_zwsp(text):
    if not text: return text
    words = word_tokenize(text, engine='newmm')
    return '\u200b'.join(words)

def create_unit_doc(unit_num, unit_name, hours, standards, core_concept, essential_q, learning, local_learning, tasks, plans, filename):
    doc = docx.Document()
    for section in doc.sections:
        section.top_margin = Cm(1.5)
        section.bottom_margin = Cm(1.5)
        section.left_margin = Cm(2.0)
        section.right_margin = Cm(2.0)

    style = doc.styles['Normal']
    font = style.font
    font.name = 'TH Sarabun New'
    font.size = Pt(16)

    def add_p(text, bold=False, align=WD_ALIGN_PARAGRAPH.LEFT):
        p = doc.add_paragraph()
        p.alignment = align
        run = p.add_run(insert_zwsp(text))
        run.font.name = 'TH Sarabun New'
        run.font.size = Pt(16)
        run.bold = bold
        return p

    # PAGE 1
    add_p(f"หน่วยการเรียนรู้ที่ {unit_num}", bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    add_p(f"ชื่อหน่วย {unit_name} รหัสวิชา ศ21101 ชื่อรายวิชา ดนตรี 1")
    add_p(f"ชั้นมัธยมศึกษาปีที่ 1 ภาคเรียนที่ 1 เวลา {hours} ชั่วโมง")
    add_p("กลุ่มสาระการเรียนรู้ ศิลปะ โรงเรียนพะเยาพิทยาคม")
    add_p("-" * 80)
    add_p("1. มาตรฐานการเรียนรู้/ตัวชี้วัด", bold=True)
    add_p("   " + standards)
    add_p("2. สาระสำคัญและคำถามสำคัญ", bold=True)
    add_p("   2.1 สาระสำคัญ: " + core_concept)
    add_p("   2.2 คำถามสำคัญ: " + essential_q)
    add_p("3. สาระการเรียนรู้", bold=True)
    add_p("   3.1 สาระการเรียนรู้แกนกลาง")
    add_p("       " + learning)
    add_p("   3.2 สาระการเรียนรู้ท้องถิ่น (ถ้ามี)")
    add_p("       " + local_learning)
    
    # PAGE 2
    doc.add_page_break()
    add_p("4. สมรรถนะสำคัญของผู้เรียน", bold=True)
    add_p("   4.1 ความสามารถในการสื่อสาร   4.2 ความสามารถในการคิด\n   4.3 ความสามารถในการแก้ปัญหา   4.4 ความสามารถในการใช้ทักษะชีวิต\n   4.5 ความสามารถในการใช้เทคโนโลยี")
    add_p("5. คุณลักษณะอันพึงประสงค์", bold=True)
    add_p("   5.1 รักชาติ ศาสน์ กษัตริย์    5.2 ซื่อสัตย์สุจริต\n   5.3 มีวินัย                5.4 ใฝ่เรียนรู้\n   5.5 อยู่อย่างพอเพียง         5.6 มุ่งมั่นในการทำงาน\n   5.7 รักความเป็นไทย         5.8 มีจิตสาธารณะ")
    add_p("6. ชิ้นงาน/ภาระงาน", bold=True)
    add_p("   " + tasks)
    add_p("7. การวัดและประเมินผล", bold=True)
    add_p("   ตรวจชิ้นงาน สังเกตพฤติกรรม และประเมินทักษะปฏิบัติด้วย Rubrics ที่วัดพฤติกรรมรูปธรรม")

    # PAGE 3
    doc.add_page_break()
    add_p("8. กิจกรรมการเรียนรู้", bold=True)
    add_p("   การจัดการเรียนรู้เชิงรุก (Active Learning) ด้วยรูปแบบ T-PACE Framework ควบคู่กับแอปพลิเคชัน และใช้เทคนิคจัดการเรียนรู้แบบแบ่งระดับ (Differentiated Instruction)")
    add_p("9. สื่อ/แหล่งการเรียนรู้", bold=True)
    add_p("   9.1 เครื่องดนตรีคาลิมบ้า (Kalimba) และเปียโนสำหรับครู")
    add_p("   9.2 ไฟล์รูปภาพโน้ตเพลง/แท็บคาลิมบ้า และไฟล์เสียง/คลิปวิดีโอสาธิต")
    add_p("   9.3 แอปพลิเคชันจูนเสียง (Tuner) และแอปพลิเคชันเมโทรนอม (Metronome)")
    add_p("   9.4 จอโปรเจคเตอร์ และ Web Application (MusicSmart)")

    # PAGE 4
    doc.add_page_break()
    add_p(f"ตารางสรุปแผนการจัดการเรียนรู้ หน่วยที่ {unit_num} ({hours} ชั่วโมง)", bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
    table = doc.add_table(rows=1, cols=7)
    table.style = 'Table Grid'
    headers = ["แผนที่/เรื่อง", "จุดประสงค์ (K,P,A)", "ชิ้นงาน", "วิธีสอนและกิจกรรม", "กลวิธีการสอน", "สื่อการเรียนรู้", "วิธีวัด/เครื่องมือ"]
    for i, h in enumerate(headers): table.rows[0].cells[i].text = insert_zwsp(h)
    
    for r in plans:
        row = table.add_row().cells
        for i in range(7): row[i].text = insert_zwsp(r[i])
        
    doc.save(os.path.join(os.getcwd(), filename))

