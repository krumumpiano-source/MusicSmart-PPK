function pRows(p) {
  const w = WHAT[p];
  const bpm = (W.M1[p].topic.match(/(\d+\s*-\s*\d+)\s*BPM/) || [])[1] || '';
  const withMet = bpm ? `กับเมโทรนอม ${bpm.replace(/\s/g, '')} BPM` : 'กับเมโทรนอม';
  const sing = w.sing ? ' และร้องให้ตรงทำนอง' : '';
  const L = {
    4: `เล่น${w.task}ถูกตำแหน่งลิ่มครบทุก${w.unit} (ไม่ผิด ไม่ข้าม) และเล่น${withMet}ได้ตรงจังหวะต่อเนื่องตลอดแบบฝึก${sing} เสียงใสไม่บอด`,
    3: `เล่นถูกตำแหน่งลิ่มเป็นส่วนใหญ่ (ผิดหรือข้ามไม่เกิน 2 ${w.unit}) และเล่น${withMet}ตรงจังหวะเป็นส่วนใหญ่ สะดุดหรือหลุดจังหวะไม่เกิน 1 ครั้ง${sing}`,
    2: `เล่นถูกตำแหน่งลิ่มเพียงบางส่วน (ผิดหรือข้าม 3-4 ${w.unit}) หรือจังหวะยังแกว่ง ต้องให้ครูให้สัญญาณหรือเล่นช้าลงจึงเล่นต่อได้${sing ? ' ร้องตรงทำนองได้บางวรรค' : ''}`,
    1: `เล่นถูกตำแหน่งลิ่มไม่ถึงครึ่งของแบบฝึก หรือไม่สามารถเล่น${withMet}ต่อเนื่องได้ แม้ครูช่วยกำกับ${sing ? ' และร้องไม่ตรงทำนอง' : ''}`
  };
  return L;
}
