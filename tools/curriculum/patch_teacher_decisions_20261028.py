def run(apply_):
    stamp = datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    files = {}
    for dp, _, fs in os.walk(P.DOC_DIR):
        for f in sorted(fs):
            if f.endswith('.docx') and not f.startswith('~$') and 'วก5' in f:
                files[P.period_of(f)] = os.path.join(dp, f)
    if apply_:
        bk = os.path.join(P.ROOT, 'scratch', 'docx_backup_' + stamp + '_teacher_decisions')
        shutil.copytree(P.DOC_DIR, bk); print('BACKUP', bk.encode('ascii', 'replace').decode())
    log, bad = [], 0
    for per in sorted(set(r[0] for r in R)):
        doc = Document(files[per])
        pars = list(P.iter_pars(doc))
        for (p_, rule, before, after) in [r for r in R if r[0] == per]:
            hit = 0
            for p in pars:
                if after in P.ntext(p):
                    continue
                for old, new in P.sub(p, re.compile(re.escape(before)), lambda m, a=after: a):
                    hit += 1
                    log.append({'period': per, 'rule': rule, 'old': old, 'new': new})
            if not hit:
                done = any(after in P.ntext(p) for p in pars)
                if not done:
                    bad += 1
                    log.append({'period': per, 'rule': rule, 'MISS': before})
                    print('MISS P%d %s: %s' % (per, rule, before[:60].encode('ascii', 'replace').decode()))
        if apply_:
            doc.save(files[per])
    out = os.path.join(P.ROOT, 'tools', 'curriculum', 'logs', 'patch_teacher_decisions_%s%s.json' % (stamp, '' if apply_ else '_dry'))
    os.makedirs(os.path.dirname(out), exist_ok=True)
    json.dump({'apply': apply_, 'changes': log, 'missing': bad}, open(out, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    n = len([x for x in log if 'old' in x])
    print('changes=%d missing=%d log=%s' % (n, bad, os.path.relpath(out, P.ROOT)))
    return bad


TITLE_RX = re.compile(r'(สังคมท้องถิ่น)\s+กรณีศึกษา(\s+และการมอบหมายงานกลุ่ม)')


def run_text(files, apply_):
    """ข้อ 4: ไฟล์ข้อความ (md / plans_data_korsor4.py ฯลฯ) — ตัด 'กรณีศึกษา' ออกจากชื่อเรื่องคาบ 18 เท่านั้น"""
    stamp = datetime.datetime.now().strftime('%Y%m%d_%H%M%S')
    bk = os.path.join(P.ROOT, 'scratch', 'backup_' + stamp + '_teacher_decisions_text')
    for f in files:
        raw = open(f, 'rb').read()
        t = raw.decode('utf-8')
        n = len(TITLE_RX.findall(t))
        print(os.path.basename(f).encode('ascii', 'replace').decode(), 'hits=%d' % n)
        if n and apply_:
            os.makedirs(bk, exist_ok=True)
            shutil.copy2(f, os.path.join(bk, os.path.basename(f)))
            open(f, 'wb').write(TITLE_RX.sub(lambda m: m.group(1) + m.group(2), t).encode('utf-8'))
            print('  แก้แล้ว สำรองที่', bk.encode('ascii', 'replace').decode())


if __name__ == '__main__':
    if '--text' in sys.argv:
        i = sys.argv.index('--text')
        run_text([a for a in sys.argv[i + 1:] if not a.startswith('--')], '--apply' in sys.argv)
    else:
        sys.exit(1 if run('--apply' in sys.argv) else 0)
